# Entries of the script's never-touch list that a user may replace with another app (their own
# dialer, keyboard, mail app ...). The app lets these be frozen after a warning, and refuses only
# while the package is the phone's current default for that job. Everything else on the
# never-touch list, and the system base, stays locked.
REPLACEABLE = {
    "com.google.android.apps.messaging",
    "com.google.android.calendar",
    "com.google.android.contacts",
    "com.google.android.dialer",
    "com.google.android.gm",
    "com.google.android.inputmethod.latin",
}

def lists_from_bat(path):
    text = open(path, encoding="utf-8").read().replace("\r\n", "\n")
    out = {}
    for key in ("SAFE_LIST", "OPT_LIST", "NEVER_LIST", "APPOPS_LIST", "CRITICAL"):
        m = re.search(r'^set "%s=([^"]*)"$' % key, text, re.M)
        if not m:
            sys.exit("list %s not found in %s" % (key, path))
        out[key] = m.group(1).split()
    return out

def main():
    bat = lists_from_bat("oneplus_cleanup.bat")
    packages = []
    for key, kind in (("SAFE_LIST", "safe"), ("OPT_LIST", "optional"), ("NEVER_LIST", "never")):
        for pkg in bat[key]:
            if pkg not in INFO:
                sys.exit("no description for " + pkg)
            name, de, en = INFO[pkg]
            entry = {"id": pkg, "list": kind, "name": name, "de": de, "en": en}
            if kind == "never" and pkg not in REPLACEABLE:
                entry["locked"] = True
            packages.append(entry)
    listed = {p["id"] for p in packages}
    extra = set(INFO) - listed
    if extra:
        sys.exit("descriptions without list entry: " + ", ".join(sorted(extra)))
    catalog = {
        "version": 1,
        "critical": bat["CRITICAL"],
        "appOpsPackages": bat["APPOPS_LIST"],
        "appOps": ["RUN_ANY_IN_BACKGROUND", "RUN_IN_BACKGROUND", "WAKE_LOCK"],
        "packages": packages,
    }
    target = "android/app/src/main/assets/catalog.json"
    with open(target, "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("wrote %s: %d packages" % (target, len(packages)))

if __name__ == "__main__":
    main()
